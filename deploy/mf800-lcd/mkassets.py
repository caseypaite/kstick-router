#!/usr/bin/env python3
"""Generate lcdassets.go: anti-aliased glyph and icon alpha masks for the MF800 status screen.

Fonts: Noto Sans (SIL OFL 1.1). Icons: Font Awesome Free 7 solid SVGs (CC BY 4.0, https://fontawesome.com).
Rendered once on the PC (PIL + rsvg-convert), so the stick needs no font engine.

  npm pack @fortawesome/fontawesome-free && tar -xzf fortawesome-fontawesome-free-*.tgz
  python3 -I mkassets.py /usr/share/fonts/noto package/svgs/solid > ../../lcdassets.go && gofmt -w ../../lcdassets.go
"""
import base64
import io
import subprocess
import sys

from PIL import Image, ImageDraw, ImageFont

# name, file, pixel size, characters
FONTS = [
    ("fontSmall", "NotoSans-Medium.ttf", 10, None),
    ("fontMed", "NotoSans-Medium.ttf", 13, None),
    ("fontBig", "NotoSans-Bold.ttf", 18, None),
    ("fontClock", "NotoSans-Bold.ttf", 28, "0123456789: "),
]

# Font Awesome solid icon, pixel height
ICONS = [
    ("tower-cell", 12), ("tower-cell", 26),
    ("bolt", 10), ("bolt", 16),
    ("globe", 18), ("globe", 14),
    ("temperature-half", 20),
    ("arrow-down", 14), ("arrow-up", 14),
    ("house", 14), ("wifi", 14), ("users", 14), ("sim-card", 14), ("plug", 14),
    ("microchip", 14), ("memory", 14), ("hard-drive", 14), ("gauge-high", 14),
    ("smog", 14), ("location-dot", 14),
]


def b64(data):
    return base64.b64encode(bytes(data)).decode()


def font_go(name, path, size, chars):
    f = ImageFont.truetype(path, size)
    asc, desc = f.getmetrics()
    h = asc + desc
    out = bytearray()
    for code in range(32, 127):
        ch = chr(code)
        if chars is not None and ch not in chars:
            out += bytes([0, 0, 0])
            continue
        adv = round(f.getlength(ch))
        pad = size
        im = Image.new("L", (adv + 2 * pad, h), 0)
        ImageDraw.Draw(im).text((pad, asc), ch, font=f, fill=255, anchor="ls")
        cols = [x for x in range(im.width) if any(im.getpixel((x, y)) for y in range(h))]
        if not cols:
            out += bytes([adv, 0, 0])
            continue
        x0, x1 = cols[0], cols[-1] + 1
        xoff = x0 - pad
        out += bytes([adv, xoff & 0xFF, x1 - x0])
        for y in range(h):
            for x in range(x0, x1):
                out.append(im.getpixel((x, y)))
    return f'var {name} = mustSmoothFont({h}, {asc}, "{b64(out)}")'


def icon_go(svgdir, name, size):
    png = subprocess.run(["rsvg-convert", "-h", str(size), f"{svgdir}/{name}.svg"], check=True, capture_output=True).stdout
    im = Image.open(io.BytesIO(png)).convert("RGBA")
    a = im.getchannel("A")
    return f'\t"{name}/{size}": mustAlphaIcon({im.width}, {im.height}, "{b64(a.tobytes())}"),'


def main():
    fontdir, svgdir = sys.argv[1], sys.argv[2]
    lines = ["// Code generated by deploy/mf800-lcd/mkassets.py. DO NOT EDIT.",
             "// Fonts: Noto Sans (SIL Open Font License 1.1). Icons: Font Awesome Free 7 (CC BY 4.0, fontawesome.com).",
             "", "package main", ""]
    for name, file, size, chars in FONTS:
        lines.append(font_go(name, f"{fontdir}/{file}", size, chars))
    lines += ["", "var lcdIcons = map[string]alphaIcon{"]
    for name, size in ICONS:
        lines.append(icon_go(svgdir, name, size))
    lines.append("}")
    print("\n".join(lines))


if __name__ == "__main__":
    main()

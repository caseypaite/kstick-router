#!/bin/sh
# Build the XP-style web UI from xp/src into ../web-xp (the three files router-webui serves for ui_style "xp").
# deploy.sh and kstick.sh run this; web-xp/ is committed too, like web/.
set -eu
cd "$(dirname "$0")"
OUT=../web-xp
mkdir -p "$OUT"
cp src/index.html "$OUT/index.html"
cp src/style.css "$OUT/style.css"
{ printf "'use strict';\n/* KStick XP — generated by xp/build.sh from xp/src/pages.js + xp/src/shell.js; edit those. */\n"
  sed "1{/^'use strict';\$/d}" src/pages.js
  cat src/shell.js; } > "$OUT/app.js.tmp"
# no timestamp in the output: an unchanged UI must not be re-uploaded by deploy.sh
if cmp -s "$OUT/app.js.tmp" "$OUT/app.js"; then rm "$OUT/app.js.tmp"; else mv "$OUT/app.js.tmp" "$OUT/app.js"; fi
if command -v node >/dev/null; then node --check "$OUT/app.js"; fi
# the server's CSP forbids inline scripts/styles: make sure none slipped into index.html
if grep -qiE '<script>|<script [^>]*>[^<]|<style|on(click|load|submit)=' "$OUT/index.html"; then
  echo "xp/build.sh: index.html has inline script/style — not allowed by the router's CSP" >&2; exit 1
fi

// ---------------- firewall ----------------

func init() { ifaceNames["lan"] = lanIf }

func nftIface(dir, role string) string {
	if n, ok := ifaceNames[role]; ok {
		return fmt.Sprintf(`%s "%s"`, dir, n)
	}
	return ""
}

func nftAddr(dir, v string) string {
	if v == "" {
		return ""
	}
	if isV4(v) {
		return fmt.Sprintf("ip %s %s", dir, v)
	}
	return fmt.Sprintf("ip6 %s %s", dir, v)
}

func nftPorts(p string) string {
	if strings.Contains(p, ",") {
		return "{ " + strings.ReplaceAll(p, ",", ", ") + " }"
	}
	return p
}

func nftProto(proto, dport string) string {
	switch proto {
	case "tcp", "udp":
		if dport != "" {
			return fmt.Sprintf("%s dport %s", proto, nftPorts(dport))
		}
		return "meta l4proto " + proto
	case "tcp/udp":
		if dport != "" {
			return "meta l4proto { tcp, udp } th dport " + nftPorts(dport)
		}
		return "meta l4proto { tcp, udp }"
	case "icmp":
		return "meta l4proto { icmp, ipv6-icmp }"
	}
	return ""
}

func join(parts ...string) string {
	out := parts[:0]
	for _, p := range parts {
		if p != "" {
			out = append(out, p)
		}
	}
	return strings.Join(out, " ")
}

func renderRule(r Rule, idx int) string {
	action := r.Action
	if action == "reject" {
		action = "reject with icmpx type admin-prohibited"
	}
	logStmt := ""
	if r.Log {
		logStmt = fmt.Sprintf(`log prefix "router-rule%d: " level info`, idx)
	}
	return join(nftIface("iifname", r.In), nftIface("oifname", r.Out), nftAddr("saddr", r.Src), nftAddr("daddr", r.Dst),
		nftProto(r.Proto, r.DPort), "counter", logStmt, action, fmt.Sprintf(`comment "%s"`, r.Comment))
}

// meshIf is the Cloudflare One client (Mesh node) tunnel interface.
const meshIf = "CloudflareWARP"

func renderFirewall(c Config) string {
	if isClient(c) {
		return renderFirewallClient(c)
	}
	lan := c.LAN.prefix()
	lanNet, lanIP := lan.Masked().String(), lan.Addr().String()
	f := c.Firewall
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format+"\n", a...) }

	w("#!/usr/sbin/nft -f")
	w("# Generated by router-webui at %s — edit through the web UI, not by hand.", time.Now().Format(time.RFC3339))
	w("# Interfaces: LAN %s (%s), MGMT/uplink usb0, WAN wwan* (LTE), VPN wg*.", lanIf, lanNet)
	w("# No 'flush ruleset': other tables (iptables-nft MSS clamp) are left alone.")
	fwHeader(w, f.Blocked)

	// blocked clients: dropped before anything else (no LAN, no internet)
	w("\n\tchain prerouting_filter {")
	w("\t\ttype filter hook prerouting priority -150; policy accept;")
	w("\t\tiifname \"%s\" ether saddr @blocked_mac counter drop comment \"blocked clients\"", lanIf)
	w("\t}")

	// port forwards (DNAT) from the uplinks
	w("\n\tchain prerouting_nat {")
	w("\t\ttype nat hook prerouting priority dstnat; policy accept;")
	for _, pf := range f.PortForwards {
		if !pf.Enabled {
			continue
		}
		to := pf.IntIP
		if pf.IntPort != "" {
			to += ":" + pf.IntPort
		}
		for _, wan := range []string{"wwan*", "usb0"} {
			w("\t\t%s", join(fmt.Sprintf(`iifname "%s"`, wan), nftAddr("saddr", pf.Source), nftProto(pf.Proto, pf.ExtPort),
				"counter dnat ip to "+to, fmt.Sprintf(`comment "%s"`, pf.Comment)))
		}
	}
	w("\t}")

	// input
	w("\n\tchain input {")
	w("\t\ttype filter hook input priority filter; policy drop;")
	w("\t\tiifname \"lo\" accept")
	w("\t\ticmpv6 type { destination-unreachable, packet-too-big, time-exceeded, parameter-problem, nd-router-advert, nd-router-solicit, nd-neighbor-solicit, nd-neighbor-advert, mld-listener-query, mld-listener-report, mld2-listener-report } accept")
	w("\t\tct state established,related accept")
	w("\t\tct state invalid drop")
	w("\t\ticmp type { destination-unreachable, time-exceeded, parameter-problem } accept")
	w("\t\tiifname \"usb0\" accept comment \"management link (always allowed)\"")
	w("\t\tiifname \"%s\" udp dport { 53, 67, 547 } accept comment \"DNS, DHCP, DHCPv6\"", lanIf)
	w("\t\tiifname \"%s\" tcp dport { 53, 80, 443 } accept comment \"DNS, web UI (always allowed)\"", lanIf)
	for i, r := range f.Rules {
		if r.Enabled && r.Chain == "input" {
			w("\t\t%s", renderRule(r, i+1))
		}
	}
	w("\t\tiifname \"%s\" jump lan_input", lanIf)
	if f.MeshAdmin {
		w("\t\t# Cloudflare Mesh (Zero Trust org devices) may manage the router")
		w("\t\tiifname \"%s\" tcp dport { 22, 80, 443 } accept comment \"SSH, web UI over Cloudflare Mesh\"", meshIf)
		w("\t\tiifname \"%s\" icmp type echo-request accept", meshIf)
		w("\t\tiifname \"%s\" icmpv6 type echo-request accept", meshIf)
	}
	if f.WANPing {
		w("\t\tiifname \"wwan*\" icmp type echo-request limit rate 5/second accept")
		w("\t\tiifname \"wwan*\" icmpv6 type echo-request limit rate 5/second accept")
	}
	w("\t\tiifname \"wwan*\" ip6 saddr fe80::/10 udp dport 546 accept comment \"DHCPv6 client\"")
	if f.LogDropped {
		w("\t\tlimit rate 5/second log prefix \"router-drop-in: \" level info")
	}
	w("\t\tcounter comment \"dropped input\"")
	w("\t}")

	w("\n\tchain lan_input {")
	if f.LANSSH {
		w("\t\ttcp dport 22 accept comment \"SSH from LAN\"")
	}
	w("\t\ticmp type echo-request accept")
	w("\t\ticmpv6 type echo-request accept")
	w("\t\treject with icmpx type admin-prohibited")
	w("\t}")

	// forward
	w("\n\tchain forward {")
	w("\t\ttype filter hook forward priority filter; policy drop;")
	w("\t\tiifname \"%s\" update @lan_tx { ip saddr } comment \"per-client upload accounting\"", lanIf)
	w("\t\toifname \"%s\" update @lan_rx { ip daddr } comment \"per-client download accounting\"", lanIf)
	w("\t\tct state established,related accept")
	w("\t\tct state invalid drop")
	w("\t\tct status dnat accept comment \"port forwards\"")
	for i, r := range f.Rules {
		if r.Enabled && r.Chain == "forward" {
			w("\t\t%s", renderRule(r, i+1))
		}
	}
	if f.MeshLAN {
		w("\t\tiifname \"%s\" oifname \"%s\" ip daddr %s accept comment \"Cloudflare Mesh -> LAN\"", meshIf, lanIf, lanNet)
	}
	w("\t\t# LAN IPv6 (ULA) may only leave through the WireGuard tunnel (NAT66)")
	w("\t\tiifname \"%s\" meta nfproto ipv6 oifname \"wwan*\" reject with icmpx type admin-prohibited", lanIf)
	w("\t\tiifname \"%s\" meta nfproto ipv6 oifname \"usb0\" reject with icmpx type admin-prohibited", lanIf)
	w("\t\tiifname \"%s\" meta nfproto ipv6 oifname \"bnep*\" reject with icmpx type admin-prohibited", lanIf)
	w("\t\t# LAN clients may open any outbound flow (VPN / WARP / IPsec / OpenVPN pass through)")
	w("\t\tiifname \"%s\" oifname \"wwan*\" accept", lanIf)
	w("\t\tiifname \"%s\" oifname \"usb0\" accept", lanIf)
	w("\t\tiifname \"%s\" oifname \"bnep*\" accept comment \"Bluetooth backup uplink (phone)\"", lanIf)
	w("\t\tiifname \"%s\" oifname \"wg*\" accept", lanIf)
	w("\t\tiifname \"%s\" oifname \"%s\" accept", lanIf, lanIf)
	if f.LogDropped {
		w("\t\tlimit rate 5/second log prefix \"router-drop-fwd: \" level info")
	}
	w("\t\tcounter comment \"dropped forward\"")
	w("\t}")

	// NAT
	w("\n\tchain postrouting {")
	w("\t\ttype nat hook postrouting priority srcnat; policy accept;")
	w("\t\toifname \"wwan*\" ip saddr %s masquerade", lanNet)
	w("\t\toifname \"usb0\" ip saddr %s masquerade", lanNet)
	w("\t\toifname \"bnep*\" ip saddr %s masquerade", lanNet)
	w("\t\toifname \"wg*\" ip saddr %s masquerade", lanNet)
	if c.IPv6.Enabled {
		w("\t\toifname \"wg*\" ip6 saddr %s masquerade comment \"LAN IPv6 via tunnel (NAT66)\"", c.IPv6.ULA)
	}
	w("\t}")
	w("}")
	_ = lanIP
	return b.String()
}

// fwHeader: the start of table inet router shared by both modes: the sets the status pages read and the
// LTE byte counters wan-failover and the data usage meter need.
func fwHeader(w func(string, ...any), blocked []Blocked) {
	w("table inet router")
	w("delete table inet router")
	w("table inet router {")
	w("\tset lan_tx {\n\t\ttype ipv4_addr\n\t\tflags dynamic,timeout\n\t\tcounter\n\t\tsize 1024\n\t\ttimeout 1d\n\t}")
	w("\tset lan_rx {\n\t\ttype ipv4_addr\n\t\tflags dynamic,timeout\n\t\tcounter\n\t\tsize 1024\n\t\ttimeout 1d\n\t}")
	w("\tset blocked_mac {\n\t\ttype ether_addr")
	if len(blocked) > 0 {
		macs := make([]string, len(blocked))
		for i, x := range blocked {
			macs[i] = x.MAC
		}
		w("\t\telements = { %s }", strings.Join(macs, ", "))
	}
	w("\t}")
	// The modem driver (bam-dmux) keeps no byte counters for wwan0 (/sys and /proc/net/dev stay 0), so LTE
	// traffic is counted here: wan-failover skips its health ping while both counters move.
	w("\tcounter lte_rx {\n\t}")
	w("\tcounter lte_tx {\n\t}")
	w("\n\tchain lte_count_in {")
	w("\t\ttype filter hook prerouting priority -300; policy accept;")
	w("\t\tiifname \"wwan0\" counter name \"lte_rx\"")
	w("\t}")
	w("\n\tchain lte_count_out {")
	w("\t\ttype filter hook postrouting priority 300; policy accept;")
	w("\t\toifname \"wwan0\" counter name \"lte_tx\"")
	w("\t}")
}

// renderFirewallClient: Wi-Fi client mode. wlan0 is an uplink (the joined network), like wwan0: nothing
// is forwarded or NATed; the device itself is reachable over USB, Cloudflare Mesh (mesh_admin) and, with
// client.lan_admin, from the joined network.
func renderFirewallClient(c Config) string {
	f := c.Firewall
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format+"\n", a...) }
	w("#!/usr/sbin/nft -f")
	w("# Generated by router-webui at %s — edit through the web UI, not by hand.", time.Now().Format(time.RFC3339))
	w("# Wi-Fi client mode: uplinks wlan0 (Wi-Fi %q) and wwan* (LTE), management usb0, no LAN.", c.Client.SSID)
	w("# No 'flush ruleset': other tables (Cloudflare WARP, iptables-nft MSS clamp) are left alone.")
	fwHeader(w, nil)
	w("\n\tchain input {")
	w("\t\ttype filter hook input priority filter; policy drop;")
	w("\t\tiifname \"lo\" accept")
	w("\t\ticmpv6 type { destination-unreachable, packet-too-big, time-exceeded, parameter-problem, nd-router-advert, nd-router-solicit, nd-neighbor-solicit, nd-neighbor-advert, mld-listener-query, mld-listener-report, mld2-listener-report } accept")
	w("\t\tct state established,related accept")
	w("\t\tct state invalid drop")
	w("\t\ticmp type { destination-unreachable, time-exceeded, parameter-problem } accept")
	w("\t\tiifname \"usb0\" accept comment \"management link (always allowed)\"")
	w("\t\tiifname \"wlan0\" udp dport 68 accept comment \"DHCP client\"")
	w("\t\tiifname { \"wlan0\", \"wwan*\" } ip6 saddr fe80::/10 udp dport 546 accept comment \"DHCPv6 client\"")
	if c.Client.LANAdmin {
		w("\t\tiifname \"wlan0\" tcp dport { 22, 80, 443 } accept comment \"SSH, web UI from the joined Wi-Fi network\"")
		w("\t\tiifname \"wlan0\" icmp type echo-request accept")
		w("\t\tiifname \"wlan0\" icmpv6 type echo-request accept")
	}
	if f.MeshAdmin {
		w("\t\t# Cloudflare Mesh (Zero Trust org devices) may manage the device")
		w("\t\tiifname \"%s\" tcp dport { 22, 80, 443 } accept comment \"SSH, web UI over Cloudflare Mesh\"", meshIf)
		w("\t\tiifname \"%s\" icmp type echo-request accept", meshIf)
		w("\t\tiifname \"%s\" icmpv6 type echo-request accept", meshIf)
	}
	if f.WANPing {
		w("\t\tiifname \"wwan*\" icmp type echo-request limit rate 5/second accept")
		w("\t\tiifname \"wwan*\" icmpv6 type echo-request limit rate 5/second accept")
	}
	if f.LogDropped {
		w("\t\tlimit rate 5/second log prefix \"router-drop-in: \" level info")
	}
	w("\t\tcounter comment \"dropped input\"")
	w("\t}")
	w("\n\tchain forward {")
	w("\t\ttype filter hook forward priority filter; policy drop;")
	w("\t\tcounter comment \"dropped forward\"")
	w("\t}")
	w("}")
	return b.String()
}

// applyFirewall validates the new ruleset against the kernel, swaps it in and
// rolls back to the previous file if loading fails.
func applyFirewall(c Config) error {
	newPath := fwPath + ".new"
	if err := writeAtomic(newPath, []byte(renderFirewall(c)), 0o644); err != nil {
		return err
	}
	if _, err := run(20*time.Second, "nft", "-c", "-f", newPath); err != nil {
		return fmt.Errorf("firewall check failed: %v", err)
	}
	prev, _ := os.ReadFile(fwPath)
	usageCheckpoint() // the reload restarts the LTE byte counters: count what they hold first
	if err := os.Rename(newPath, fwPath); err != nil {
		return err
	}
	if _, err := run(20*time.Second, "/usr/local/sbin/router-firewall", "reload"); err != nil {
		if prev != nil {
			_ = writeAtomic(fwPath, prev, 0o644)
			_, _ = run(20*time.Second, "/usr/local/sbin/router-firewall", "reload")
		}
		return fmt.Errorf("firewall load failed (previous ruleset restored): %v", err)
	}
	return nil
}

// ---------------- DHCP / DNS (dnsmasq) ----------------

func renderDnsmasq(c Config) string {
	lan := c.LAN.prefix()
	lanIP := lan.Addr().String()
	mask := netip.PrefixFrom(lan.Addr(), lan.Bits())
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format+"\n", a...) }
	w("# Generated by router-webui at %s — edit through the web UI.", time.Now().Format(time.RFC3339))
	w("interface=%s", lanIf)
	w("except-interface=lo")
	w("bind-dynamic")
	w("domain-needed")
	w("bogus-priv")
	w("no-resolv")
	w("no-hosts")
	w("cache-size=1000")
	w("# OS update blocking (DNS page): reloaded on SIGHUP when the uplink changes")
	w("servers-file=%s", updateBlockPath)
	w("domain=lan")
	w("local=/lan/")
	w("expand-hosts")
	if dev := dnsTunnel(c); dev != "" {
		w("# the LAN is routed through %s, so its DNS goes through it too (nothing leaks over the WAN)", dev)
	} else if len(c.DNS.Upstreams) == 0 {
		w("# follow the active WAN's DNS through the system resolver")
	}
	for _, u := range dnsUpstreams(c) {
		w("server=%s", u)
	}
	if c.DNS.RebindProtection {
		w("stop-dns-rebind")
		w("rebind-localhost-ok")
		w("rebind-domain-ok=/lan/")
	}
	if h, _ := os.Hostname(); reHostname.MatchString(h) && h != "router" {
		w("host-record=router.lan,router,%s.lan,%s,%s", h, h, lanIP)
	} else {
		w("host-record=router.lan,router,%s", lanIP)
	}
	for _, h := range c.DNS.Hosts {
		w("host-record=%s,%s", h.Name, h.IP)
	}
	for _, d := range c.DNS.Blocklist {
		w("address=/%s/0.0.0.0", d)
		w("address=/%s/::", d)
	}
	if c.IPv6.Enabled {
		lifetime := 0 // not a default router while the tunnel is down
		if v6TunnelUp.Load() {
			lifetime = 1800
		}
		w("# IPv6: ULA prefix from %s, SLAAC + RDNSS, MTU of the WireGuard tunnel", lanIf)
		w("enable-ra")
		w("dhcp-range=::,constructor:%s,ra-stateless,ra-names,12h", lanIf)
		w("ra-param=%s,mtu:1280,30,%d", lanIf, lifetime)
		w("dhcp-option=option6:dns-server,[::]")
	}
	if c.LAN.DHCPEnabled {
		w("dhcp-authoritative")
		w("dhcp-range=%s,%s,%s,%s", c.LAN.DHCPStart, c.LAN.DHCPEnd, prefixMask(mask.Bits()), c.LAN.LeaseTime)
		w("dhcp-option=option:router,%s", lanIP)
		w("dhcp-option=option:dns-server,%s", lanIP)
		w("dhcp-leasefile=%s", leasePath)
		for _, l := range c.LAN.Static {
			if l.Name != "" {
				w("dhcp-host=%s,%s,%s", l.MAC, l.IP, l.Name)
			} else {
				w("dhcp-host=%s,%s", l.MAC, l.IP)
			}
		}
	}
	return b.String()
}

// dnsUpstreams: dnsmasq server values for dnsmasq.conf and the update-block servers-file. While the
// LAN goes through a tunnel (vpn.go), every upstream is bound to it; only IPv4 servers work there.
func dnsUpstreams(c Config) []string {
	dev := dnsTunnel(c)
	if dev == "" {
		if len(c.DNS.Upstreams) == 0 {
			return []string{"127.0.0.1"} // the system resolver, which follows the active WAN's DNS
		}
		return c.DNS.Upstreams
	}
	var out []string
	for _, u := range c.DNS.Upstreams {
		if isV4(u) {
			out = append(out, u+"@"+dev)
		}
	}
	if len(out) == 0 {
		for _, u := range defaultTunnelDNS {
			out = append(out, u+"@"+dev)
		}
	}
	return out
}

func prefixMask(bits int) string {
	m := uint32(0xffffffff) << (32 - bits)
	return fmt.Sprintf("%d.%d.%d.%d", m>>24, (m>>16)&0xff, (m>>8)&0xff, m&0xff)
}

var dnsmasqMu sync.Mutex

// applyDnsmasq writes the DHCP/DNS config and restarts dnsmasq. In client mode dnsmasq must not run at
// all (it would serve DHCP on the network the device joined), so it is stopped instead.
func applyDnsmasq(c Config) error {
	if isClient(c) {
		stopDnsmasq()
		return nil
	}
	if err := writeDnsmasq(c); err != nil {
		return err
	}
	dnsmasqMu.Lock()
	defer dnsmasqMu.Unlock()
	if _, err := run(20*time.Second, "systemctl", "restart", "router-dnsmasq"); err != nil {
		return err
	}
	// wait until DNS answers again so the next request (or diagnostics) doesn't race the restart
	addr := net.JoinHostPort(c.LAN.prefix().Addr().String(), "53")
	for i := 0; i < 30; i++ {
		if conn, err := net.DialTimeout("tcp", addr, 200*time.Millisecond); err == nil {
			conn.Close()
			break
		}
		time.Sleep(100 * time.Millisecond)
	}
	return nil
}

// writeDnsmasq validates and installs the dnsmasq config without (re)starting dnsmasq.
func writeDnsmasq(c Config) error {
	dnsmasqMu.Lock()
	defer dnsmasqMu.Unlock()
	if _, err := writeUpdateBlock(c); err != nil { // the servers-file must exist before dnsmasq starts
		return err
	}
	newPath := dnsmasqPath + ".new"
	if err := writeAtomic(newPath, []byte(renderDnsmasq(c)), 0o644); err != nil {
		return err
	}
	if _, err := run(10*time.Second, "dnsmasq", "--test", "--conf-file="+newPath); err != nil {
		return fmt.Errorf("dnsmasq config check failed: %v", err)
	}
	return os.Rename(newPath, dnsmasqPath)
}

// ---------------- WAN failover ----------------

func renderWANConf(c Config) string {
	return fmt.Sprintf(`# Generated by router-webui — edit through the web UI.
WANS="%s"
TARGETS="%s"
INTERVAL=%d
FAIL_AFTER=%d
`, strings.Join(wanList(c), " "), strings.Join(c.WAN.Targets, " "), c.WAN.Interval, c.WAN.FailAfter)
}

func applyWAN(c Config) error {
	if err := writeAtomic(wanConfPath, []byte(renderWANConf(c)), 0o644); err != nil {
		return err
	}
	_, err := run(20*time.Second, "systemctl", "restart", "wan-failover")
	return err
}

// renderAll writes every generated file (after validating each) without reloading services.
// Used once by the installer.
func renderAll() {
	c := snapshot()
	if _, err := writeUpdateBlock(c); err != nil {
		log.Fatal(err)
	}
	files := []struct{ path, data, check string }{
		{fwPath, renderFirewall(c), "nft"},
		{dnsmasqPath, renderDnsmasq(c), "dnsmasq"},
		{wanConfPath, renderWANConf(c), ""},
	}
	for _, f := range files {
		tmp := f.path + ".new"
		if err := writeAtomic(tmp, []byte(f.data), 0o644); err != nil {
			log.Fatal(err)
		}
		var err error
		switch f.check {
		case "nft":
			_, err = run(20*time.Second, "nft", "-c", "-f", tmp)
		case "dnsmasq":
			_, err = run(10*time.Second, "dnsmasq", "--test", "--conf-file="+tmp)
		}
		if err != nil {
			log.Fatalf("%s: %v", f.path, err)
		}
		if err := os.Rename(tmp, f.path); err != nil {
			log.Fatal(err)
		}
		log.Printf("wrote %s", f.path)
	}
}
